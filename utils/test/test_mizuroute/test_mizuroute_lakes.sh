#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Test of mizuRoute lakes in the coupled SUMMA-mizuRoute build
#
# Runs the bundled Provo domain with water-class HRUs and Doll and HYPE lakes, see
# mizuroute_lake_test.py for the setup. It checks that precipitation and Oudin
# evaporation reach the lakes, that each lake's water balance closes, and then
# routes what the coupled run sent through standalone mizuRoute, which must give
# the same streamflow and storage.
#
# The standalone step needs bin/route_runoff, see make_mizuRoute.sh, and is
# reported as SKIPPED without it.
#
# Requires a build configured with -DUSE_MIZUROUTE=ON, and python3 with netCDF4.
#
# Usage: ./test_mizuroute_lakes.sh [work_dir]
# ==============================================================================

# ------------------------------------------------------------------ settings --
SUMMA_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# the executable name records the build options, with or without SUNDIALS
SUMMA_EXE="$SUMMA_ROOT/bin/summa_sundials_mizuroute.exe"
[[ -f "$SUMMA_EXE" ]] || SUMMA_EXE="$SUMMA_ROOT/bin/summa_mizuroute.exe"
ROUTE_EXE="$SUMMA_ROOT/bin/route_runoff"
DOMAIN="$SUMMA_ROOT/utils/test/test_ngen/domain_provo"
FILE_MANAGER="$DOMAIN/settings/SUMMA/fileManager.txt"
FORCING="$DOMAIN/forcing/SUMMA_input/ngen_forcings_summa_format.nc"
TOOL="$TEST_DIR/mizuroute_lake_test.py"

WORK_DIR="${1:-$TEST_DIR/lake_test}"
SUFFIX="lakes"
SIM_END="2017-11-30 23:00"

if [[ ! -f "$SUMMA_EXE" ]]; then
  echo "ERROR: no mizuRoute executable in $SUMMA_ROOT/bin"
  echo "       this test needs a mizuRoute build: cmake -B cmake_build -S build -DUSE_MIZUROUTE=ON"
  exit 1
fi

mkdir -p "$WORK_DIR/output" "$WORK_DIR/standalone/output"

# --------------------------------------------------------------------- domain --
python3 "$TOOL" build "$DOMAIN/settings/SUMMA" "$WORK_DIR"
cp "$SUMMA_ROOT/external/mizuRoute/route/ancillary_data/param.nml.default" "$WORK_DIR/mizu/"

cat > "$WORK_DIR/config.toml" <<EOF
# generated by test_mizuroute_lakes.sh

[simulation]

use_mizuroute = true

[mizuRoute]

namelist_path = "$WORK_DIR/mizu/"
namelist_file = "param.nml.default"

methods = "3"

dt = 3600

is_lake_sim = true

write_qbasin = true
write_Qreach = true

[hydrofabric]

hfabric_path = "$WORK_DIR/mizu/"
hfabric_file = "topology.nc"

dname_seg = "seg"
dname_hru = "hru"

varname_HRUid     = "hruId"
varname_segId     = "segId"
varname_hruSegId  = "hruToSegId"
varname_downSegId = "downSegId"

varname_area   = "area"
varname_slope  = "slope"
varname_length = "length"

[remapping]

remap_path = "$WORK_DIR/mizu/"
remap_file = "remap.nc"

dname_hru  = "polyid"
dname_data = "data"

vname_hruid    = "polyid"
vname_weight   = "weight"
vname_num_qhru = "nOverlaps"
vname_qhruid   = "qhru_id"
EOF

sed -e "s|^settingsPath .*|settingsPath         '$WORK_DIR/settings/'|" \
    -e "s|^forcingPath .*|forcingPath          '$DOMAIN/forcing/SUMMA_input/'|" \
    -e "s|^outputPath .*|outputPath           '$WORK_DIR/output/'|" \
    -e "s|^simEndTime .*|simEndTime           '$SIM_END'|" \
    "$FILE_MANAGER" > "$WORK_DIR/fileManager.txt"

# ---------------------------------------------------------------- coupled run --
echo
echo "Running coupled SUMMA-mizuRoute with lakes..."
"$SUMMA_EXE" -m "$WORK_DIR/fileManager.txt" -c "$WORK_DIR/config.toml" -s "$SUFFIX" \
             > "$WORK_DIR/run.log" 2>&1 || true
if ! grep -q "finished simulation successfully" "$WORK_DIR/run.log"; then
  echo "ERROR: run did not complete; see $WORK_DIR/run.log"
  tail -20 "$WORK_DIR/run.log"
  exit 1
fi

OUTPUT=$(ls "$WORK_DIR/output/"*"${SUFFIX}"*timestep.nc | head -1)
echo
echo "Checking the coupled run..."
python3 "$TOOL" check "$OUTPUT" "$WORK_DIR" "$FORCING"

# ------------------------------------------------------------- standalone run --
echo
if [[ ! -x "$ROUTE_EXE" ]]; then
  echo "Standalone comparison SKIPPED: $ROUTE_EXE not found, see make_mizuRoute.sh"
  echo
  echo "PASS (coupled checks only)"
  exit 0
fi

echo "Routing the same inputs through standalone mizuRoute..."
python3 "$TOOL" standalone-input "$OUTPUT" "$WORK_DIR"
echo "forcing.nc" > "$WORK_DIR/standalone/forcing_list.txt"
cp "$WORK_DIR/mizu/param.nml.default" "$WORK_DIR/standalone/"

# the first and last output times of the coupled run
read -r SIM_START_OUT SIM_END_OUT < <(python3 - "$OUTPUT" <<'PYEOF'
import sys
from netCDF4 import Dataset, date2num, num2date
with Dataset(sys.argv[1]) as o:
    units = "hours since 2017-01-01 00:00:00"
    hours = date2num(num2date(o["time"][[0, -1]], o["time"].units), units).round()
    dates = num2date(hours, units)
    print(dates[0].strftime("%Y-%m-%dT%H:%M:%S"), dates[1].strftime("%Y-%m-%dT%H:%M:%S"))
PYEOF
)

# read_control requires a "!" ending every entry
sed -e '/^</ s/$/ !/' > "$WORK_DIR/standalone/lakes.control" <<EOF
! generated by test_mizuroute_lakes.sh, matching the coupled configuration
<case_name>               lakes
<sim_start>               ${SIM_START_OUT/T/ }
<sim_end>                 ${SIM_END_OUT/T/ }
<route_opt>               3
<doesBasinRoute>          0
<dt_qsim>                 3600
<is_lake_sim>             T
<LakeInputOption>         2
<restart_write>           never
<ancil_dir>               $WORK_DIR/mizu/
<input_dir>               $WORK_DIR/standalone/
<output_dir>              $WORK_DIR/standalone/output/
<fname_ntopOld>           topology.nc
<dname_sseg>              seg
<dname_nhru>              hru
<fname_qsim>              forcing_list.txt
<vname_qsim>              runoff
<vname_precip>            precip
<vname_evapo>             evap
<vname_time>              time
<vname_hruid>             hruId
<dname_time>              time
<dname_hruid>             hru
<units_qsim>              m/s
<dt_ro>                   3600
<ro_time_stamp>           start
<is_remap>                T
<fname_remap>             remap.nc
<vname_hruid_in_remap>    polyid
<vname_weight>            weight
<vname_qhruid>            qhru_id
<vname_num_qhru>          nOverlaps
<dname_hru_remap>         polyid
<dname_data_remap>        data
<param_nml>               param.nml.default
<varname_area>            area
<varname_length>          length
<varname_slope>           slope
<varname_HRUid>           hruId
<varname_hruSegId>        hruToSegId
<varname_segId>           segId
<varname_downSegId>       downSegId
<varname_islake>          islake
<varname_lakeModelType>   LakeModelType
<pio_netcdf_type>         netcdf
<newFileFrequency>        single
<outputFrequency>         1
<basRunoff>               F
<instRunoff>              F
<dlayRunoff>              F
<sumUpstreamRunoff>       F
<KWroutedRunoff>          T
<KWvolume>                T
EOF

"$ROUTE_EXE" "$WORK_DIR/standalone/lakes.control" > "$WORK_DIR/standalone/run.log" 2>&1 || {
  echo "ERROR: standalone mizuRoute failed; see $WORK_DIR/standalone/run.log"
  tail -20 "$WORK_DIR/standalone/run.log"
  exit 1
}

STANDALONE=$(ls "$WORK_DIR/standalone/output/"lakes.h.*.nc | head -1)
echo
echo "Comparing coupled and standalone mizuRoute..."
python3 "$TOOL" compare "$OUTPUT" "$STANDALONE"

echo
echo "PASS"
