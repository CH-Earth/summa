#!/bin/bash
# ---------------------------------------------------------------------------------------
# Two-objective calibration test on the bundled Bow at Banff (CAN_05BB001) domain.
#
# The same domain and period as test_calibration_bow.sh, scored against two
# targets: daily discharge (KGE) and the GRACE storage anomaly (RMSE). The same sample
# budget is spent twice - by NSGA-II on the two objectives, and by DDS on their weighted
# sum - and the script checks the NSGA-II front, then compares what each search found.
#
# The budget is tiny, so this exercises the machinery; it does not settle which search is
# better. Needs an executable built with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON.
#
# Usage:  ./test_calibration_bow_pareto.sh [population] [generations] [n_ranks]
# ---------------------------------------------------------------------------------------
set -euo pipefail

TEST_DIR="$(cd "$(dirname "$0")" && pwd)"
SUMMA_ROOT="$(cd "${TEST_DIR}/../../.." && pwd)"
DATA="${SUMMA_ROOT}/utils/test/test_mizuroute/bow_real_data"
WORK="${TEST_DIR}/bow_pareto"

POPULATION=${1:-8}
GENERATIONS=${2:-5}
N_RANKS=${3:-5}
N_SAMPLES=$((POPULATION * GENERATIONS))

# DDS weight on GRACE RMSE (mm) against discharge KGE: 100 mm counts as one unit of KGE
GRACE_WEIGHT=0.01

SUMMA_EXE="${SUMMA_ROOT}/bin/summa_sundials_mizuroute_opt.exe"
if [ ! -x "${SUMMA_EXE}" ]; then
  SUMMA_EXE="${SUMMA_ROOT}/bin/summa_mizuroute_opt.exe"
fi
if [ ! -x "${SUMMA_EXE}" ]; then
  echo "ERROR: no calibration executable found in ${SUMMA_ROOT}/bin"
  echo "       build one with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON"
  exit 1
fi

echo "======================================================================"
echo "SUMMA two-objective calibration test (Bow at Banff, discharge + GRACE)"
echo "======================================================================"
echo "  executable:  ${SUMMA_EXE}"
echo "  work dir:    ${WORK}"
echo "  budget:      ${N_SAMPLES} trials (population ${POPULATION} x ${GENERATIONS} generations)"
echo "  ranks:       ${N_RANKS}"
echo

rm -rf "${WORK}"

