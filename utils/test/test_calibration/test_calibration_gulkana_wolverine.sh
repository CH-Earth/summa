#!/bin/bash
# ---------------------------------------------------------------------------------------
# Multi-objective calibration over two GRUs: Gulkana (GRU 1) and Wolverine (GRU 2) glaciers.
#
# NSGA-II on each basin's routed discharge (KGE) and its GRACE storage anomaly (RMSE, relative to the run
# period), Oct 2016 - Jul 2018 after a spin-up from Oct 2015, over six snow, glacier and groundwater
# parameters. It tests that a calibration scores several targets on several GRUs and reaches; the budget is
# tiny, so it calibrates nothing.
#
# Needs an executable built with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON. Each GRU drains to its own reach:
# reach 1 below Gulkana Glacier, reach 2 below Wolverine Glacier.
#
# Usage:  ./test_calibration_gulkana_wolverine.sh [population] [generations] [n_ranks]
# ---------------------------------------------------------------------------------------
set -euo pipefail

TEST_DIR="$(cd "$(dirname "$0")" && pwd)"
SUMMA_ROOT="$(cd "${TEST_DIR}/../../.." && pwd)"
DATA="${TEST_DIR}/gulkana_wolverine"
WORK="${TEST_DIR}/gulkana_wolverine_run"

POPULATION=${1:-4}
GENERATIONS=${2:-3}
N_RANKS=${3:-5}
N_SAMPLES=$((POPULATION * GENERATIONS))

SUMMA_EXE=""
for exe in summa_sundials_mizuroute_opt.exe summa_mizuroute_opt.exe; do
  if [ -x "${SUMMA_ROOT}/bin/${exe}" ]; then SUMMA_EXE="${SUMMA_ROOT}/bin/${exe}"; break; fi
done
if [ -z "${SUMMA_EXE}" ]; then
  echo "ERROR: no calibration executable with mizuRoute found in ${SUMMA_ROOT}/bin"
  echo "       build one with -DUSE_MPI=ON -DUSE_MIZUROUTE=ON"
  exit 1
fi

echo "======================================================================"
echo "SUMMA two-GRU calibration test (discharge + GRACE on Gulkana and Wolverine)"
echo "======================================================================"
echo "  executable:  ${SUMMA_EXE}"
echo "  work dir:    ${WORK}"
echo "  budget:      ${N_SAMPLES} trials (population ${POPULATION} x ${GENERATIONS} generations)"
echo "  ranks:       ${N_RANKS}"
echo

rm -rf "${WORK}"
mkdir -p "${WORK}/output" "${WORK}/state"
cp "${DATA}/summa_inputs/coldState.nc" "${WORK}/state/"
cat > "${WORK}/config.toml" <<EOF
# generated by test_calibration_gulkana_wolverine.sh

[simulation]

case_name = "gulkana_wolverine"

# one spinup year (Oct 2015 - Sep 2016) precedes the simulation, which the calibration then scores
start_time = "2016-10-01 00:00"
end_time   = "2018-07-31 23:00"
time_zone  = "utcTime"

use_mizuroute    = true
write_timeseries = false

work_path = "${WORK}/output"


[summa_files]

settings_path = "${DATA}/summa_inputs/"
forcing_path  = "${DATA}/forcing/"
state_path    = "${WORK}/state/"
output_path   = "${WORK}/output/"

init_condition = "coldState.nc"
attributes     = "attributes.nc"
forcing_list   = "forcingFileList.txt"

decisions        = "modelDecisions.txt"
output_control   = "outputControl.txt"
trial_params     = "trialParams.nc"
local_parameters = "localParamInfo.txt"
basin_parameters = "basinParamInfo.txt"

vegetation_table = "TBL_VEGPARM.TBL"
soil_table       = "TBL_SOILPARM.TBL"
general_table    = "TBL_GENPARM.TBL"
noahmp_table     = "TBL_MPTABLE.TBL"


[mizuRoute]

namelist_path = "${DATA}/"
namelist_file = "mizuroute.param"

methods = "3"
dt      = 3600

write_qbasin = false
write_Qreach = false


[hydrofabric]

hfabric_path = "${DATA}/"
hfabric_file = "topology.nc"

dname_seg = "seg"
dname_hru = "hru"

varname_HRUid     = "hruId"
varname_segId     = "segId"
varname_hruSegId  = "hruToSegId"
varname_downSegId = "downSegId"

varname_area   = "area"
varname_slope  = "slope"
varname_length = "length"


[calibration]

algorithm = "nsga2"

start_date = "2016-10-01"
end_date   = "2018-07-31"

n_samples = ${N_SAMPLES}

param_list = [
    "frozenPrecipMultip",
    "tempCritRain",
    "glacierWindFactor",
    "glacierTempReduction",
    "albedoMax",
    "aquiferBaseflowExp"
]

write_aligned = false


[calibration.nsga2]

population_size = ${POPULATION}


[[calibration.target]]

name      = "gulkana_discharge"
variable  = "streamflow"
reach     = 1
obs_path  = "${DATA}/observations/"
obs_file  = "gulkana_USGS_15478040_daily_flow.nc"
vname_obs = "q_obs"
metric    = "kge"


[[calibration.target]]

name      = "wolverine_discharge"
variable  = "streamflow"
reach     = 2
obs_path  = "${DATA}/observations/"
obs_file  = "wolverine_USGS_15236900_daily_flow.nc"
vname_obs = "q_obs"
metric    = "kge"


[[calibration.target]]

name      = "gulkana_grace"
variable  = "basin__StorageChange"
gru       = 1
obs_path  = "${DATA}/observations/"
obs_file  = "gulkana_grace_tws.nc"
vname_obs = "tws_obs"
metric    = "rmse"
accumulate     = true
baseline_start = "2016-10-01"
baseline_end   = "2018-07-31"


[[calibration.target]]

name      = "wolverine_grace"
variable  = "basin__StorageChange"
gru       = 2
obs_path  = "${DATA}/observations/"
obs_file  = "wolverine_grace_tws.nc"
vname_obs = "tws_obs"
metric    = "rmse"
accumulate     = true
baseline_start = "2016-10-01"
baseline_end   = "2018-07-31"

EOF

echo "Running nsga2..."
set +e
mpirun -np "${N_RANKS}" "${SUMMA_EXE}" -c "${WORK}/config.toml" > "${WORK}/run.log" 2>&1
status=$?
set -e
if [ ${status} -ne 0 ]; then
  echo "FAIL: calibration exited ${status}"
  echo "--- last 25 lines of ${WORK}/run.log ---"
  tail -25 "${WORK}/run.log"
  exit 1
fi
grep -E "^NSGA-II generation" "${WORK}/run.log" | sed 's/^/  /' || true
echo

echo "Checking the NSGA-II front..."
python3 - "${WORK}" "${POPULATION}" "${GENERATIONS}" <<'PYEOF'
import os, sys
import numpy as np
import netCDF4 as nc

work, pop, ngen = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
names = ['gulkana_discharge', 'wolverine_discharge', 'gulkana_grace', 'wolverine_grace']
senses = ['maximize', 'maximize', 'minimize', 'minimize']

d = nc.Dataset(os.path.join(work, "output", "gulkana_wolverine_run0001_calibration.nc"))
sense = [s.strip() for s in d["objective"].sense.split(",")]
obj = np.ma.filled(d["objective"][:].astype(float), np.nan).T   # (target, sample)
failed = np.asarray(d["trial_failed"][:]) == 1

def nondominated(f):
    n = f.shape[1]
    keep = np.ones(n, bool)
    for i in range(n):
        for j in range(n):
            if np.all(f[:, j] <= f[:, i]) and np.any(f[:, j] < f[:, i]):
                keep[i] = False
                break
    return keep

fail = False
def check(ok, what):
    global fail
    print(f"  {'ok  ' if ok else 'FAIL'} {what}")
    fail |= not ok

check(d.algorithm == "nsga2", "trials file records algorithm nsga2")
check(obj.shape == (len(names), pop * ngen), f"objective is {len(names)} targets x {pop * ngen} trials")
check(sense == senses, "each target is oriented as its metric says: " + ", ".join(f"{n} {s}" for n, s in zip(names, senses)))
check(bool(np.any(~failed)), f"{int((~failed).sum())} of {failed.size} trials ran")
check(bool(np.all(np.isfinite(obj[:, ~failed]))), "every objective of a trial that ran is finite")

# smaller is better on every row; a failed trial is the worst on every target
f = np.array([-o if s == "maximize" else o for o, s in zip(obj, sense)])
f[:, failed] = np.inf
front = np.asarray(d["pareto_front"][:]) == 1
check(bool(np.array_equal(front, nondominated(f))), "pareto_front flags exactly the non-dominated trials")

population = np.asarray(d["population"][:]) - 1
rank = np.asarray(d["population_rank"][:])
check(population.shape == (ngen, pop), f"population is {ngen} generations x {pop} members")
check(bool(np.all(front[population[-1][rank[-1] == 1]])), "the final population's first front is non-dominated overall")

nf = int(front.sum())
check(nf >= 1, f"the front holds {nf} trial(s)")

print()
print(f"  NSGA-II front ({nf} trials):")
print("    sample  " + "  ".join(f"{n:>18s}" for n in names))
for i in np.where(front)[0]:
    print(f"    {i + 1:6d}  " + "  ".join(f"{v:18.4g}" for v in obj[:, i]))
print(f"  failed trials (saved in output/failed_trials): {int(failed.sum())}")

sys.exit(1 if fail else 0)
PYEOF

echo
echo "PASS"
